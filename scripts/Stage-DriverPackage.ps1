#Requires -Version 5.1
<#
.SYNOPSIS
    Stages the driver package directory and writes the unsigned-build notice.

.DESCRIPTION
    Copies the built .sys and the INF into artifacts\package\<platform>\<config>.
    The catalog is generated separately by Invoke-Inf2Cat.ps1. Nothing is
    signed and nothing is installed.
#>
[CmdletBinding()]
param(
    [ValidateSet('Debug', 'Release')]
    [string]$Configuration = 'Release',

    [ValidateSet('x64')]
    [string]$Platform = 'x64'
)

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$buildDir = Join-Path $repoRoot "artifacts\driver\$Platform\$Configuration"
$packageDir = Join-Path $repoRoot "artifacts\package\$Platform\$Configuration"
$sysPath = Join-Path $buildDir 'STGRExt4.sys'
$infPath = Join-Path $repoRoot 'driver\STGRExt4.inf'

if (-not (Test-Path -LiteralPath $sysPath)) {
    throw "Driver binary not found: $sysPath"
}

if ((Get-Item -LiteralPath $sysPath).Length -le 0) {
    throw "Driver binary is empty: $sysPath"
}

if (-not (Test-Path -LiteralPath $infPath)) {
    throw "INF not found: $infPath"
}

New-Item -ItemType Directory -Force -Path $packageDir | Out-Null

Copy-Item -LiteralPath $sysPath -Destination (Join-Path $packageDir 'STGRExt4.sys') -Force
Copy-Item -LiteralPath $infPath -Destination (Join-Path $packageDir 'STGRExt4.inf') -Force

$unsignedNotice = @"
STGR EXT4 - UNSIGNED DEVELOPMENT BUILD
======================================

This package was produced by an automated build. It is NOT signed with a
Microsoft-trusted production certificate.

  * Windows 11 x64 will not load this driver in normal mode.
  * A test-signed build requires TESTSIGNING and a test certificate installed
    on a disposable test machine. That is not a production configuration.
  * Do not install this package on a machine that contains data you care
    about. Do not point it at a real Linux root filesystem.

The .cat file in this directory, if present, was generated by Inf2Cat but is
not signed.

See docs/DRIVER-SIGNING.md and docs/DRIVER-INSTALLATION.md.
"@

Set-Content -LiteralPath (Join-Path $packageDir 'README-UNSIGNED.txt') -Value $unsignedNotice -Encoding ASCII

Get-ChildItem -LiteralPath $packageDir | Select-Object Name, Length | Format-Table -AutoSize
